_NOT_AUTHORIZED = re.compile(r"not authorized to grant permissions:\s*(.+)", re.IGNORECASE | re.DOTALL)


def is_forbidden(error: dict | None) -> bool:
    return isinstance(error, dict) and error.get("type") == "forbidden"


def refused_permissions(error: dict | None) -> set[str]:
    """The permissions a `forbidden` SetError names as not grantable (may be empty)."""
    if not is_forbidden(error):
        return set()
    m = _NOT_AUTHORIZED.search(error.get("description") or "")
    if not m:
        return set()
    return {p for p in re.split(r"[\s,]+", m.group(1).strip().rstrip(".")) if p}


def replace_permissions(exclude: set[str] = frozenset()) -> dict:
    """An x:CredentialPermissions value granting the interoperable set, minus `exclude`."""
    return {
        "@type": "Replace",
        "permissions": {p: True for p in INTEROPERABLE_PERMISSIONS if p not in exclude},
    }
