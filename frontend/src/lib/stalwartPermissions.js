/** True for a SetError of type `forbidden`. */
export function isForbidden(error) {
  return error?.type === 'forbidden';
}

/** The permissions a `forbidden` SetError names as not grantable (may be empty). */
export function refusedPermissions(error) {
  if (!isForbidden(error)) return new Set();
  const m = /not authorized to grant permissions:\s*([\s\S]+)/i.exec(error.description ?? '');
  if (!m) return new Set();
  return new Set(m[1].trim().replace(/\.$/, '').split(/[\s,]+/).filter(Boolean));
}

/** An x:CredentialPermissions value granting the interoperable set, minus `exclude`. */
export function replacePermissions(exclude = new Set()) {
  const permissions = {};
  for (const p of INTEROPERABLE_PERMISSIONS) if (!exclude.has(p)) permissions[p] = true;
  return { '@type': 'Replace', permissions };
}
